"""Generate `docs/data_dictionary.md` from the TableSpecs."""

from __future__ import annotations

from pathlib import Path

from breeding_smarter.io.paths import repo_root
from breeding_smarter.schema.tables import ALL_TABLES

HEADER = """# Data dictionary

Generated by `bsm schema dictionary` from `src/breeding_smarter/schema/tables.py`.
Do not edit by hand; a test fails if this file is out of date.

All animals, kennels and identifiers in this dataset are synthetic.
"""


def render_dictionary() -> str:
    parts = [HEADER]
    for spec in ALL_TABLES:
        parts.append(f"\n## {spec.name}\n\n{spec.description}\n")
        parts.append(f"\nPrimary key: `{', '.join(spec.primary_key)}`\n")
        if spec.foreign_keys:
            fks = "; ".join(
                f"`{fk.columns[0]}` -> `{fk.ref_table}.{fk.ref_columns[0]}`"
                for fk in spec.foreign_keys
            )
            parts.append(f"\nForeign keys: {fks}\n")
        parts.append(
            "\n| Field | Type | Null | Description | Allowed values |\n|---|---|---|---|---|\n"
        )
        for f in spec.fields:
            dom = ", ".join(f.domain) if f.domain else ""
            null = "yes" if f.nullable else "no"
            parts.append(f"| {f.name} | {f.type} | {null} | {f.description} | {dom} |\n")
    return "".join(parts)


def default_path() -> Path:
    return repo_root() / "docs" / "data_dictionary.md"


def write_dictionary(path: Path | None = None) -> Path:
    p = path or default_path()
    p.write_text(render_dictionary())
    return p
