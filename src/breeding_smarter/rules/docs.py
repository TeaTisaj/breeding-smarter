"""Generate `docs/rules_catalogue.md` and `docs/rules_verification.md` from the YAML."""

from __future__ import annotations

from pathlib import Path

from breeding_smarter.config.sourced import source_refs
from breeding_smarter.io.paths import repo_root
from breeding_smarter.rules.loader import available_profiles, load_profile, load_spec

COMPOSITES = ("hr_full", "uk_full", "nl_full")


def _sources() -> dict[str, str]:
    """Source key -> reference, as a Markdown link when `configs/sources.yaml` gives a `url`."""
    return {k: f"[{ref}]({url})" if url else ref for k, (ref, url) in source_refs().items()}


def render_catalogue() -> str:
    src = _sources()
    lines = [
        "# Rules catalogue",
        "",
        "Generated by `bsm rules docs` from `configs/rules/*.yaml`. Do not edit by hand.",
        "Rules marked **unverified** have not been checked against the primary legal text; the",
        "demo app shows an 'unverified' badge next to them.",
        "",
        "| Profile | Rule | Type | Parameters | Severity | Source | Article | Verified | Note |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name in available_profiles():
        spec = load_spec(name)
        for r in spec.rules:
            params = ", ".join(f"{k}={v}" for k, v in r.params.items())
            ver = "yes" if r.verified else "**unverified**"
            lines.append(
                f"| {name} | {r.id} | {r.type} | {params} | {r.severity} | "
                f"{r.source} | {r.article or ''} | {ver} | {r.note or ''} |"
            )
    lines += ["", "## Composite profiles", ""]
    for c in COMPOSITES:
        p = load_profile(c)
        lines.append(f"- **{c}** ({p.title}): {', '.join(m for m in p.members if m != c)}")
    lines += ["", "## Sources", ""]
    used = sorted({r.source for n in available_profiles() for r in load_spec(n).rules})
    lines += [f"- `{k}`: {src.get(k, '')}" for k in used]
    return "\n".join(lines) + "\n"


def render_verification() -> str:
    src = _sources()
    lines = [
        "# Rules verification checklist [HUMAN]",
        "",
        "Generated by `bsm rules docs` from `configs/rules/*.yaml`. For every rule below, check",
        "the primary text, fill `article` (and `in_application_from` for EU 2026/1818), correct",
        "the parameters if needed, then set `verified: true` and regenerate the docs.",
        "",
    ]
    for name in available_profiles():
        spec = load_spec(name)
        todo = [r for r in spec.rules if not r.verified]
        if name == "eu_2026_1818" and spec.in_application_from is None:
            lines += [
                f"## {name}: application date",
                "",
                "- [ ] Fill `in_application_from` and transition periods from the OJ "
                "text (eur-lex.europa.eu/eli/reg/2026/1818). Press reports mention 4 years "
                "for breeders and sellers (UNVERIFIED).",
                "",
            ]
        if not todo:
            continue
        lines += [f"## {name} ({spec.title})", ""]
        for r in todo:
            params = ", ".join(f"{k}={v}" for k, v in r.params.items())
            lines.append(
                f"- [ ] `{r.id}` ({r.type}: {params}, {r.severity}). Current source: "
                f"`{r.source}` ({src.get(r.source, '')}). {r.note or ''}"
            )
            if r.source in ("euroweekly-2026", "catster-2026"):
                lines.append(
                    "  - Press report only: find the article in the OJ text "
                    "(eurlex-2026-1818) and replace the source key."
                )
            if r.source == "hks-pravilnik":
                lines.append("  - Check the current HKS Pravilnik o uzgoju for non-hunting breeds.")
        lines.append("")
    lines += [
        "## Not yet encoded",
        "",
        "- [ ] HKS minimum interval between litters: add a `min_interval_between_litters` "
        "rule to `hks_hr.yaml` only if the Pravilnik states one.",
        "- [ ] EU 2026/1818 Annex I 3.2: no breeding of a bitch before her second oestrus. "
        "Needs oestrus records, which the registry schema does not have.",
        "- [ ] EU 2026/1818 Annex I 3.4: at least one year of recuperation after three "
        "litters (stillborns included) in two years. Needs a new rule type.",
        "- [ ] EU 2026/1818 Annex I 3.6: veterinary check in writing before breeding a bitch "
        "aged 8 or more (a manual check, not a ban).",
        "",
    ]
    return "\n".join(lines) + "\n"


def write_docs(root: Path | None = None) -> list[Path]:
    d = (root or repo_root()) / "docs"
    out = []
    for fname, text in (
        ("rules_catalogue.md", render_catalogue()),
        ("rules_verification.md", render_verification()),
    ):
        (d / fname).write_text(text)
        out.append(d / fname)
    return out
