def write_zenodo_metadata(tag: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(zenodo_metadata(tag), indent=2, ensure_ascii=False) + "\n")
    return path


PLACEHOLDERS = ("TODO-DOI", "TODO-HF", "TODO-CONTACT", "TODO-DEMO-URL", "https://github.com/TODO/")
SCAN = ("README.md", "CITATION.cff", "docs", "app", "conference", "release/zenodo_metadata.json")


def find_placeholders(root: Path | None = None) -> list[tuple[str, int, str]]:
    """Every remaining link placeholder (file, line, text)."""
    root = root or repo_root()
    hits = []
    for item in SCAN:
        p = root / item
        files = [p] if p.is_file() else sorted(p.rglob("*")) if p.is_dir() else []
        for f in files:
            if not f.is_file() or f.suffix not in (".md", ".py", ".cff", ".json", ".yaml"):
                continue
            if f.name == "links.yaml":
                continue
            for i, line in enumerate(f.read_text(errors="ignore").splitlines(), 1):
                if any(ph in line for ph in PLACEHOLDERS):
                    hits.append((str(f.relative_to(root)), i, line.strip()))
    return hits


def fill_placeholders(root: Path | None = None) -> int:
    """Replace placeholders with the values in `conference/links.yaml` (non-empty only)."""
    root = root or repo_root()
    lk = links()
    mapping = {
        "TODO-DOI": lk.get("dataset_doi", ""),
        "TODO-HF": lk.get("huggingface", ""),
        "TODO-CONTACT": lk.get("contact", ""),
        "TODO-DEMO-URL": lk.get("demo_url", ""),
        "https://github.com/TODO/breeding-smarter": lk.get("github", ""),
    }
    mapping = {k: v for k, v in mapping.items() if v and "TODO" not in v}
    changed = 0
    for f, _, _ in find_placeholders(root):
        path = root / f
        text = path.read_text()
        new = text
        for k, v in mapping.items():
            new = new.replace(k, v)
        if new != text:
            path.write_text(new)
            changed += 1
    return changed
