def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def export_release(tag: str = "v1", out_root: Path | None = None) -> Path:
    run = resolve_dataset(tag)
    root = out_root or repo_root() / "release"
    name = f"breeding-smarter-synthetic-{tag}"
    out = root / name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / "README.md").write_text(render_card(tag))
    sheet = render_datasheet(tag)
    (out / "datasheet.md").write_text(sheet)
    (repo_root() / "docs" / "datasheet.md").write_text(sheet)
    (out / "data_dictionary.md").write_text(render_dictionary())
    shutil.copy(repo_root() / "LICENSE-DATA", out / "LICENSE")
    from breeding_smarter.io.parquet import read_table

    for group, specs in (("registry", REGISTRY_TABLES), ("truth", TRUTH_TABLES)):
        (out / group).mkdir()
        (out / f"{group}_csv").mkdir()
        for spec in specs:
            shutil.copy(run.table(spec), out / spec.filename)
            df = read_table(run.table(spec), spec)
            base = spec.name.split("/")[1]
            df.to_csv(
                out / f"{group}_csv" / f"{base}.csv.gz",
                index=False,
                compression={"method": "gzip", "mtime": 0},
            )
    val = repo_root() / "reports" / "validation" / run.run_id
    if val.is_dir():
        shutil.copytree(val, out / "validation")
    shutil.copytree(run.config_snapshot, out / "config_snapshot")
    shutil.copy(run.manifest, out / "manifest.json")
    files = sorted(p for p in out.rglob("*") if p.is_file())
    (out / "SHA256SUMS").write_text("".join(f"{_sha256(p)}  {p.relative_to(out)}\n" for p in files))
    zpath = root / f"{name}.zip"
    _zip(out, zpath)
    if zpath.stat().st_size > MAX_ZIP_BYTES:
        shutil.rmtree(out / "truth_csv")
        _zip(out, zpath)
    write_zenodo_metadata(tag, root / "zenodo_metadata.json")
    return out


def _zip(folder: Path, zpath: Path) -> None:
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(folder.rglob("*")):
            if p.is_file():
                z.write(p, Path(folder.name) / p.relative_to(folder))


