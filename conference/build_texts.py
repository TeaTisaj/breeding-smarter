"""Render the conference texts from templates and numbers.json; check the poster word count.

Usage: uv run python conference/build_texts.py   (exit 1 if the poster text exceeds 300 words)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MAX_POSTER_WORDS = 300
TARGETS = {
    "poster_text.md": ROOT / "poster" / "text.md",
    "slides_outline.md": ROOT / "slides" / "outline.md",
    "demo_script.md": ROOT / "demo_script.md",
    "partner_onepager.md": ROOT / "partner_onepager.md",
    "qa.md": ROOT / "qa.md",
    "paper_draft.md": ROOT / "paper" / "draft.md",
}


def word_count(md: str) -> int:
    """Words a reader sees: markdown symbols removed, numbers and names count as words."""
    text = re.sub(r"[#*_`>|-]+", " ", md)
    return len([w for w in text.split() if re.search(r"\w", w)])


def main() -> int:
    numbers = json.loads((ROOT / "numbers.json").read_text())
    header = (
        "<!-- Generated by conference/build_texts.py from conference/templates/; "
        "numbers from conference/numbers.json. Edit the template, not this file. -->\n"
    )
    for tmpl, out in TARGETS.items():
        text = (ROOT / "templates" / tmpl).read_text().format_map(numbers)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(header + text)
        print(f"wrote {out}")
    n = word_count((ROOT / "templates" / "poster_text.md").read_text().format_map(numbers))
    print(f"poster words: {n} (limit {MAX_POSTER_WORDS})")
    return 0 if n <= MAX_POSTER_WORDS else 1


if __name__ == "__main__":
    sys.exit(main())
