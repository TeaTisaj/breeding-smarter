"""P12 performance targets (plan section 5), on a SYN_M experiment year of dataset v1.

Results are written to reports/benchmarks/coordination.md.
"""

import platform
import time

import numpy as np
import pytest

from breeding_smarter.io import repo_root

TARGET_PLAN_S = 2.0  # one plan_season with OCS for a SYN_M year
TARGET_RANK_MS = 20.0  # rank_fast per dam with quota-restricted candidates


@pytest.mark.slow
def test_coordination_speed():
    from breeding_smarter.coordination.config import load_coordination
    from breeding_smarter.coordination.planner import plan_season
    from breeding_smarter.experiments.observed import ObservedRegistry
    from breeding_smarter.experiments.runner import experiment_setup, prepared_state
    from breeding_smarter.io.datasets import resolve_dataset
    from breeding_smarter.matching import load_scoring
    from breeding_smarter.matching.recommend import rank_fast
    from breeding_smarter.rules import day_number
    from breeding_smarter.sim.demography import eligible
    from breeding_smarter.sim.genetics import DogGenetics
    from breeding_smarter.sim.state import DOMESTIC, SimState

    try:
        rp = resolve_dataset("v1")
    except Exception:
        pytest.skip("dataset v1 not available")
    state, _ = SimState.load(prepared_state("v1", "SYN_M"))
    b = state.breed_ids.index("SYN_M")
    setup = experiment_setup(rp.root, b, 1.0)
    g = DogGenetics.from_setup(setup)
    g.load_arrays(state.extra)
    obs = ObservedRegistry(state, g, setup, b)
    year = state.year + 1
    ctx = obs.context(state, year)
    day = day_number(f"{year}-07-01")
    rng = np.random.default_rng(0)
    dams = obs.idx(rng.choice(eligible(state, setup, b, DOMESTIC, year, 0, g), 150, replace=False))
    sires = obs.idx(eligible(state, setup, b, DOMESTIC, year, 1, g))
    cfg = load_coordination()
    plan_season(ctx, "SYN_M", day, dams[:5], sires[:20], cfg, "ocs", "mc1")  # warm-up
    times = []
    for _ in range(2):
        t0 = time.perf_counter()
        plan = plan_season(ctx, "SYN_M", day, dams, sires, cfg, "ocs", "mc1")
        times.append(time.perf_counter() - t0)
    t_plan = min(times)
    avail = plan.sires[plan.quotas > 0]
    scoring = load_scoring()
    rank_fast(ctx, int(dams[0]), day, "exp_pairing", scoring, candidates=avail)
    t0 = time.perf_counter()
    for d in dams[:30]:
        rank_fast(ctx, int(d), day, "exp_pairing", scoring, candidates=avail)
    t_rank = (time.perf_counter() - t0) / 30 * 1000
    lines = [
        "# Coordination benchmarks (P12)",
        "",
        "Generated by `uv run pytest -m slow tests/benchmarks/test_coordination_speed.py`.",
        f"Machine: {platform.platform()}, Python {platform.python_version()}.",
        "",
        f"SYN_M registry view of dataset v1, year {year}: {dams.size} dams, {sires.size} "
        f"candidate sires ({plan.diagnostics['n_sires_with_quota']} get a quota).",
        "",
        "| operation | time | target |",
        "|---|---|---|",
        f"| plan_season (OCS + Sainte-Laguë + MC1) | {t_plan:.2f} s | < {TARGET_PLAN_S} s |",
        f"| of which the OCS solve | {plan.diagnostics['solver_seconds']:.2f} s | |",
        f"| rank_fast per dam, quota-restricted | {t_rank:.1f} ms | < {TARGET_RANK_MS} ms |",
        "",
    ]
    out = repo_root() / "reports" / "benchmarks" / "coordination.md"
    out.write_text("\n".join(lines))
    assert t_plan < TARGET_PLAN_S, t_plan
    assert t_rank < TARGET_RANK_MS, t_rank
