"""Engine benchmarks (P2 task 2.11). Results are written to reports/benchmarks/engine.md."""

import platform
import time

import numpy as np
import pytest

from breeding_smarter.io import repo_root
from breeding_smarter.pedigree import (
    A_times,
    inbreeding,
    kinship_to_all,
    pair_kinship,
)
from tests.fixtures.random_ped import realistic_pedigree

TARGETS = {"inbreeding": 60.0, "A_times": 1.0, "kinship_to_all": 1.0, "pair_kinship": 0.010}
SIZES = [10_000, 50_000, 250_000]


def _time(fn, repeat=1):
    best = float("inf")
    for _ in range(repeat):
        t0 = time.perf_counter()
        fn()
        best = min(best, time.perf_counter() - t0)
    return best


@pytest.mark.slow
def test_engine_speed():
    warm = realistic_pedigree(2000, seed=0)
    F, D = inbreeding(warm)
    A_times(warm, D, np.ones(warm.n))
    pair_kinship(warm, F, D, warm.n - 1, warm.n - 2)
    rows = []
    for n in SIZES:
        ped = realistic_pedigree(n, seed=1)
        t_f = _time(lambda ped=ped: inbreeding(ped))
        F, D = inbreeding(ped)
        x = np.random.default_rng(0).normal(size=n)
        t_a = _time(lambda ped=ped, D=D, x=x: A_times(ped, D, x), 3)
        t_k = _time(lambda ped=ped, D=D: kinship_to_all(ped, D, ped.n - 1), 3)
        rng = np.random.default_rng(1)
        pairs = rng.integers(n - n // 10, n, size=(50, 2))
        t0 = time.perf_counter()
        for a, b in pairs:
            pair_kinship(ped, F, D, int(a), int(b))
        t_p = (time.perf_counter() - t0) / len(pairs)
        rows.append((n, t_f, t_a, t_k, t_p, float(F[-n // 10 :].mean())))
    lines = [
        "# Engine benchmarks",
        "",
        "Generated by `uv run pytest -m slow tests/benchmarks/test_speed.py`.",
        f"Machine: {platform.platform()}, {platform.processor() or platform.machine()}.",
        "Pedigree: synthetic overlapping generations, litters of 3 to 7, Pareto-weighted sires.",
        "",
        "| n | inbreeding (s) | A_times (s) | kinship_to_all (s) | pair_kinship (ms) "
        "| mean F last 10% |",
        "|---|---|---|---|---|---|",
    ]
    for n, t_f, t_a, t_k, t_p, mf in rows:
        lines.append(f"| {n:,} | {t_f:.2f} | {t_a:.3f} | {t_k:.3f} | {1000 * t_p:.2f} | {mf:.3f} |")
    lines += [
        "",
        "Targets (250k animals): inbreeding < 60 s, A_times < 1 s, kinship_to_all < 1 s, "
        "pair_kinship < 10 ms.",
    ]
    out = repo_root() / "reports" / "benchmarks" / "engine.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    n, t_f, t_a, t_k, t_p, _ = rows[-1]
    assert t_f < TARGETS["inbreeding"]
    assert t_a < TARGETS["A_times"]
    assert t_k < TARGETS["kinship_to_all"]
    assert t_p < TARGETS["pair_kinship"]
